n = 7

# -----------------------------
# Loop to print decreasing number of stars in each row
# -----------------------------
for i in range(n):
    print('* ' * (n - i))

# -----------------------------
# End of Inverted Right-Angled Star Triangle Pattern
# -----------------------------
